"""Generate the color schemes of every client from brand/tokens/.

    python scripts/tokens.py
    python scripts/tokens.py --check

Copied from canone without edits: plataformas/transversal.md, «Tema».
It reads the subset of DTCG 2025.10 that the page allows and fails on
anything else. --check writes nothing and fails if a generated file is
missing or stale.
"""

