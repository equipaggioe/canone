# WCAG 1.4.3 at 4.5:1 for every pair, large text included, and 1.4.11
# at 3:1 for the outline.
TEXT = 4.5
GRAPHIC = 3.0
PAIRS = [
    *((text, surface, TEXT) for text in ("onSurface", "onSurfaceVariant") for surface in SURFACES),
    *(
        (f"on{name}", name[0].lower() + name[1:], TEXT)
        for name in (
            "Primary",
            "PrimaryContainer",
            "Secondary",
            "SecondaryContainer",
            "Tertiary",
            "TertiaryContainer",
            "Error",
            "ErrorContainer",
            "InverseSurface",
        )
    ),
    *(
        (f"on{hue}Fixed{variant}", f"{hue.lower()}Fixed{dim}", TEXT)
        for hue in ("Primary", "Secondary", "Tertiary")
        for variant in ("", "Variant")
        for dim in ("", "Dim")
    ),
    ("inversePrimary", "inverseSurface", TEXT),
    *(("outline", surface, GRAPHIC) for surface in SURFACES),
]

ALIAS = re.compile(r"\{palette(?:\.[^.{}]+)+\}")
HEX = re.compile(r"#[0-9a-f]{6}")

type Scheme = dict[str, str]


class TokenError(Exception):
    """brand/tokens/ is outside the subset that this script reads."""


def load(path: Path) -> object:
    """Read a JSON file of brand/tokens/."""
    if not path.is_file():
        raise TokenError(f"{path.name} does not exist")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise TokenError(f"{path.name}: {error}") from error


def mapping(value: object, where: str) -> dict[str, object]:
    """Return value as a JSON object, or fail."""
    if not isinstance(value, dict):
        raise TokenError(f"{where} is not an object")
    return {str(key): item for key, item in value.items()}


def only(value: dict[str, object], allowed: set[str], where: str) -> None:
    """Fail on a key outside allowed."""
    extra = sorted(set(value) - allowed)
    if extra:
        raise TokenError(f"{where}: unsupported {', '.join(extra)}")


def sources(value: object, folder: Path, sets: dict[str, list[Path]], where: str) -> list[Path]:
    """Return the token files that a list of sources names, in order."""
    if not isinstance(value, list):
        raise TokenError(f"{where} is not a list")
    files: list[Path] = []
    for index, item in enumerate(value):
        reference = mapping(item, f"{where}[{index}]")
        only(reference, {"$ref"}, f"{where}[{index}]")
        target = reference.get("$ref")
        if not isinstance(target, str):
            raise TokenError(f"{where}[{index}] has no $ref")
        if target.startswith("#/sets/") and target[7:] in sets:
            files.extend(sets[target[7:]])
        elif target.endswith(".tokens.json") and "#" not in target:
            path = (folder / target).resolve()
            if not path.is_relative_to(folder.resolve()):
                raise TokenError(f"{where}[{index}]: {target} is outside brand/tokens/")
            files.append(path)
        else:
            raise TokenError(f"{where}[{index}]: unsupported $ref {target}")
    return files


def order(resolver: Path) -> dict[str, list[Path]]:
    """Return the token files of each mode, in resolution order."""
    root = mapping(load(resolver), resolver.name)
    only(
        root,
        {"$schema", "name", "version", "description", "sets", "modifiers", "resolutionOrder"},
        resolver.name,
    )
    if root.get("version") != "2025.10":
        raise TokenError(f"{resolver.name}: version is not 2025.10")
    folder = resolver.parent
    sets: dict[str, list[Path]] = {}
    for name, value in mapping(root.get("sets", {}), "sets").items():
        body = mapping(value, f"sets.{name}")
        only(body, {"sources", "description"}, f"sets.{name}")
        sets[name] = sources(body.get("sources"), folder, {}, f"sets.{name}.sources")
    modifiers = mapping(root.get("modifiers", {}), "modifiers")
    only(modifiers, {"theme"}, "modifiers")
    theme = mapping(modifiers.get("theme"), "modifiers.theme")
    only(theme, {"contexts", "description", "default"}, "modifiers.theme")
    contexts = mapping(theme.get("contexts"), "modifiers.theme.contexts")
    if sorted(contexts) != sorted(MODES):
        raise TokenError("modifiers.theme.contexts are not exactly light and dark")
    if "default" in theme and theme["default"] not in MODES:
        raise TokenError("modifiers.theme.default is not a context")
    steps = root.get("resolutionOrder")
    if not isinstance(steps, list) or not steps:
        raise TokenError(f"{resolver.name}: resolutionOrder is missing")
    files: dict[str, list[Path]] = {mode: [] for mode in MODES}
    seen: set[str] = set()
    for index, step in enumerate(steps):
        reference = mapping(step, f"resolutionOrder[{index}]")
        only(reference, {"$ref"}, f"resolutionOrder[{index}]")
        target = reference.get("$ref")
        if not isinstance(target, str) or target in seen:
            raise TokenError(f"resolutionOrder[{index}] is not a new $ref")
        seen.add(target)
        if target == "#/modifiers/theme":
            for mode in MODES:
                where = f"modifiers.theme.contexts.{mode}"
                files[mode].extend(sources(contexts[mode], folder, sets, where))
        elif target.startswith("#/sets/") and target[7:] in sets:
            for mode in MODES:
                files[mode].extend(sets[target[7:]])
        else:
            raise TokenError(f"resolutionOrder[{index}]: unsupported $ref {target}")
    if "#/modifiers/theme" not in seen:
        raise TokenError("resolutionOrder does not include the theme modifier")
    return files


def merge(target: dict[str, object], source: dict[str, object]) -> None:
    """Merge a token tree into another; a later token replaces a former one."""
    for key, value in source.items():
        current = target.get(key)
        if (
            isinstance(current, dict)
            and isinstance(value, dict)
            and "$value" not in current
            and "$value" not in value
        ):
            merge(current, value)
        else:
            target[key] = value


def tokens(group: dict[str, object], path: str, kind: object) -> dict[str, object]:
    """Flatten a group into {path: $value}, checking names and types."""
    only(group, {"$type", "$description"} | {k for k in group if not k.startswith("$")}, path)
    kind = group.get("$type", kind)
    found: dict[str, object] = {}
    for key, value in group.items():
        if key.startswith("$"):
            continue
        where = f"{path}.{key}"
        if set(key) & set("{}."):
            raise TokenError(f"{path}: unsupported name {key}")
        node = mapping(value, where)
        if "$value" in node:
            only(node, {"$value", "$type", "$description"}, where)
            if node.get("$type", kind) != "color":
                raise TokenError(f"{where} is not of $type color")
            found[where] = node["$value"]
        else:
            found |= tokens(node, where, kind)
    return found


def color(value: object, where: str) -> str:
    """Return an opaque sRGB color as #rrggbb, or fail."""
    body = mapping(value, where)
    only(body, {"colorSpace", "components", "alpha", "hex"}, where)
    components = body.get("components")
    if body.get("colorSpace") != "srgb":
        raise TokenError(f"{where}: colorSpace is not srgb")
    if (
        not isinstance(components, list)
        or len(components) != 3
        or not all(
            isinstance(c, int | float) and not isinstance(c, bool) and 0 <= c <= 1
            for c in components
        )
    ):
        raise TokenError(f"{where}: components are not three numbers from 0 to 1")
    if body.get("alpha", 1) != 1:
        raise TokenError(f"{where}: alpha is not 1")
    result = "#" + "".join(f"{round(c * 255):02x}" for c in components)
    fallback = body.get("hex")
    if fallback is not None and (
        not isinstance(fallback, str) or not HEX.fullmatch(fallback.lower())
    ):
        raise TokenError(f"{where}: hex is not #rrggbb")
    if isinstance(fallback, str) and fallback.lower() != result:
        raise TokenError(f"{where}: hex {fallback} is not the components ({result})")
    return result


def scheme(files: list[Path]) -> Scheme:
    """Resolve one mode into {role: #rrggbb}."""
    tree: dict[str, object] = {}
    for path in files:
        merge(tree, mapping(load(path), path.name))
    only(tree, {"palette", "color"}, "the tokens")
    found = tokens(mapping(tree.get("palette", {}), "palette"), "palette", None)
    palette = {path: color(value, path) for path, value in found.items()}
    roles = tokens(mapping(tree.get("color", {}), "color"), "color", None)
    expected = {f"color.{role}" for role in ROLES}
    if set(roles) != expected:
        missing = sorted(expected - set(roles))
        extra = sorted(set(roles) - expected)
        raise TokenError(f"color: missing {missing}, unknown {extra}")
    result: Scheme = {}
    for path, value in roles.items():
        if not isinstance(value, str) or not ALIAS.fullmatch(value):
            raise TokenError(f"{path} is not an alias of palette")
        target = value[1:-1]
        if target not in palette:
            raise TokenError(f"{path}: {value} does not exist")
        result[path.removeprefix("color.")] = palette[target]
    return {role: result[role] for role in ROLES}


def luminance(hex_color: str) -> float:
    """Return the relative luminance of WCAG 2.2."""
    channels = [int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first: str, second: str) -> float:
    """Return the contrast ratio of WCAG 2.2."""
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def check_contrast(schemes: dict[str, Scheme]) -> None:
    """Fail on a pair under its minimum ratio."""
    failures = [
        f"{mode}: {front} on {back} is {ratio:.2f}:1, under {minimum}:1"
        for mode, colors in schemes.items()
        for front, back, minimum in PAIRS
        if (ratio := contrast(colors[front], colors[back])) < minimum
    ]
    if failures:
        raise TokenError("; ".join(failures))


def snake(role: str) -> str:
    """Return a role in snake_case."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", role).lower()


def kebab(role: str) -> str:
    """Return a role in kebab-case."""
    return snake(role).replace("_", "-")


def argb(hex_color: str) -> str:
    """Return #rrggbb as an opaque 0xAARRGGBB literal."""
    return "0xFF" + hex_color[1:].upper()


def dart(schemes: dict[str, Scheme]) -> str:
    """Write the two ColorScheme of Flutter."""
    blocks = []
    for mode, colors in schemes.items():
        fields = "".join(f"  {role}: Color({argb(value)}),\n" for role, value in colors.items())
        blocks.append(
            f"const {mode}ColorScheme = ColorScheme(\n"
            f"  brightness: Brightness.{mode},\n{fields});\n"
        )
    return f"// {HEADER}\n\nimport 'package:flutter/material.dart';\n\n" + "\n".join(blocks)


# Compose names one role differently and has no shadow. It still has the
# three roles that Flutter deprecated, and would fill them with its own
# defaults.
COMPOSE = {"onInverseSurface": "inverseOnSurface", "shadow": None}
COMPOSE_EXTRA = {
    "background": "surface",
    "onBackground": "onSurface",
    "surfaceVariant": "surfaceContainerHighest",
}


def kotlin(schemes: dict[str, Scheme], package: str) -> str:
    """Write the two ColorScheme of Compose."""
    blocks = []
    for mode, colors in schemes.items():
        names = {COMPOSE.get(role, role): value for role, value in colors.items()}
        names |= {extra: colors[role] for extra, role in COMPOSE_EXTRA.items()}
        fields = ",\n".join(
            f"        {name} = Color({argb(value)})"
            for name, value in names.items()
            if name is not None
        )
        blocks.append(
            f"val {mode.title()}ColorScheme =\n    {mode}ColorScheme(\n{fields}\n    )\n"
        )
    return (
        f"// {HEADER}\n"
        f"package {package}\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n" + "\n".join(blocks)
    )


def flet(schemes: dict[str, Scheme]) -> str:
    """Write the two ColorScheme of Flet."""
    blocks = []
    for mode, colors in schemes.items():
        fields = "".join(f'    {snake(role)}="{value}",\n' for role, value in colors.items())
        blocks.append(f"{mode.upper()} = ft.ColorScheme(\n{fields})\n")
    return f'"""{HEADER}"""\n\nimport flet as ft\n\n' + "\n".join(blocks)


# The palette of Fusion. Disabled text follows Material 3: on-surface at
# 38% opacity.
QPALETTE = {
    "Window": "surface",
    "WindowText": "onSurface",
    "Base": "surfaceContainerLowest",
    "AlternateBase": "surfaceContainerLow",
    "Text": "onSurface",
    "PlaceholderText": "onSurfaceVariant",
    "Button": "surfaceContainerHigh",
    "ButtonText": "onSurface",
    "BrightText": "onPrimary",
    "Light": "surfaceBright",
    "Midlight": "surfaceContainerLow",
    "Mid": "outlineVariant",
    "Dark": "surfaceDim",
    "Shadow": "shadow",
    "Highlight": "primary",
    "HighlightedText": "onPrimary",
    "Accent": "primary",
    "Link": "primary",
    "LinkVisited": "tertiary",
    "ToolTipBase": "inverseSurface",
    "ToolTipText": "onInverseSurface",
}
DISABLED = ("WindowText", "Text", "ButtonText")


def qt(schemes: dict[str, Scheme]) -> str:
    """Write the two schemes of Qt and the function that builds a QPalette."""
    blocks = []
    for mode, colors in schemes.items():
        fields = "".join(f'    "{snake(role)}": "{value}",\n' for role, value in colors.items())
        blocks.append(f"{mode.upper()} = {{\n{fields}}}\n")
    roles = "".join(
        f'    QPalette.ColorRole.{role}: "{snake(name)}",\n' for role, name in QPALETTE.items()
    )
    disabled = "".join(f"        QPalette.ColorRole.{role},\n" for role in DISABLED)
    return (
        f'"""{HEADER}"""\n\n'
        "from PySide6.QtGui import QColor, QPalette\n\n"
        + "\n".join(blocks)
        + f"\nROLES = {{\n{roles}}}\n\n\n"
        "def palette(colors: dict[str, str]) -> QPalette:\n"
        '    """Build the palette of one mode."""\n'
        "    result = QPalette()\n"
        "    for role, name in ROLES.items():\n"
        "        result.setColor(role, QColor(colors[name]))\n"
        '    disabled = QColor(colors["on_surface"])\n'
        "    disabled.setAlphaF(0.38)\n"
        "    for role in (\n"
        f"{disabled}"
        "    ):\n"
        "        result.setColor(QPalette.ColorGroup.Disabled, role, disabled)\n"
        "    return result\n"
    )


def typescript(schemes: dict[str, Scheme]) -> str:
    """Write the UnoCSS colors and the CSS variables of both modes."""
    names = ",\n".join(f"\t{quote(kebab(role))}: 'var(--color-{kebab(role)})'" for role in ROLES)
    light = "".join(f"\t--color-{kebab(r)}: {v};\n" for r, v in schemes["light"].items())
    dark = "".join(f"\t\t--color-{kebab(r)}: {v};\n" for r, v in schemes["dark"].items())
    return (
        f"// {HEADER}\n\n"
        f"export const colors = {{\n{names}\n}};\n\n"
        "export const colorsCss = `:root {\n"
        "\tcolor-scheme: light dark;\n"
        f"{light}}}\n"
        "@media (prefers-color-scheme: dark) {\n"
        "\t:root {\n"
        f"{dark}\t}}\n"
        "}\n"
        "`;\n"
    )


def quote(key: str) -> str:
    """Quote an object key only when TypeScript needs it."""
    return key if key.isidentifier() else f"'{key}'"


def requirements(pyproject: Path) -> set[str]:
    """Return the names of the dependencies that a pyproject.toml declares."""
    data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    declared = list(data.get("project", {}).get("dependencies", []))
    return {re.split(r"[^A-Za-z0-9._-]", item, maxsplit=1)[0].lower() for item in declared}


def namespace(app: Path) -> str:
    """Return the namespace that an Android app declares."""
    build = app / "app/build.gradle.kts"
    if not build.is_file():
        raise TokenError(f"{app.name}/app/build.gradle.kts does not exist")
    found = re.search(r'namespace\s*=\s*"([\w.]+)"', build.read_text(encoding="utf-8"))
    if not found:
        raise TokenError(f"{app.name}/app/build.gradle.kts declares no namespace")
    return found.group(1)


type Writer = Callable[[dict[str, Scheme]], str]


def outputs(repo: Path) -> dict[Path, Writer]:
    """Return the generated file of every client in the repository."""
    found: dict[Path, Writer] = {}
    for pubspec in sorted(repo.glob("*/pubspec.yaml")):
        found[pubspec.parent / "lib/ui/core/themes/colors.dart"] = dart
    for settings in sorted(repo.glob("*/settings.gradle.kts")):
        package = namespace(settings.parent) + ".ui.theme"
        folder = settings.parent / "app/src/main/java" / package.replace(".", "/")
        found[folder / "Colors.kt"] = lambda schemes, package=package: kotlin(schemes, package)
    for pyproject in sorted(repo.glob("*/pyproject.toml")):
        declared = requirements(pyproject)
        if "flet" in declared:
            found[pyproject.parent / "src/colors.py"] = flet
        if "pyside6" in declared:
            found[pyproject.parent / "src/app/colors.py"] = qt
    for package_json in sorted(repo.glob("*/package.json")):
        data = json.loads(package_json.read_text(encoding="utf-8"))
        if "@sveltejs/kit" in {**data.get("dependencies", {}), **data.get("devDependencies", {})}:
            found[package_json.parent / "src/lib/colors.ts"] = typescript
    return found


def generate(repo: Path) -> dict[Path, str]:
    """Return the content of every generated file, or fail."""
    files = outputs(repo)
    if not files:
        return {}
    schemes = {mode: scheme(paths) for mode, paths in order(repo / RESOLVER).items()}
    check_contrast(schemes)
    return {path: writer(schemes) for path, writer in files.items()}


def stale(repo: Path) -> list[str]:
    """List what --check fails on."""
    try:
        files = generate(repo)
    except TokenError as error:
        return [f"brand/tokens/: {error}"]
    return [
        f"{path.relative_to(repo).as_posix()} is not up to date with brand/tokens/"
        for path, content in files.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def main() -> int:
    """Generate, or with --check, verify."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    repo = Path(__file__).resolve().parents[1]
    if parser.parse_args().check:
        failures = stale(repo)
        for failure in failures:
            print(failure, file=sys.stderr)
        return 1 if failures else 0
    try:
        files = generate(repo)
    except TokenError as error:
        print(f"brand/tokens/: {error}", file=sys.stderr)
        return 1
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
